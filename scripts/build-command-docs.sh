#!/usr/bin/env bash

# Build the operation reference from the embedded, offline runtime catalog.
set -euo pipefail

main() (
  local check_only=n repo_root output temp_dir staging=''
  case "${1:-}" in
    --check) check_only=y; shift ;;
    --help|-h)
      printf '%s\n' 'Usage: bash scripts/build-command-docs.sh [--check]' \
        'Generate the Wiki command catalog from install.sh agent commands --json.' \
        '--check compares the generated reference without changing repository files.'
      return 0
      ;;
  esac
  [[ $# -eq 0 ]] || { printf 'ERROR: expected no arguments or --check\n' >&2; return 2; }
  repo_root=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd -P) || return 1
  output="${repo_root}/docs/wiki/Command-Catalog.md"
  [[ ! -L "${output}" && ( ! -e "${output}" || -f "${output}" ) ]] || {
    printf 'ERROR: command reference must be a regular file\n' >&2; return 1;
  }
  umask 077
  temp_dir=$(mktemp -d) || return 1
  cleanup_command_docs() {
    rm -rf -- "${temp_dir}"
    [[ -z "${staging}" ]] || rm -f -- "${staging}"
  }
  trap cleanup_command_docs EXIT
  bash "${repo_root}/install.sh" agent commands --json > "${temp_dir}/catalog.json" || return 1
  python3 - "${temp_dir}/catalog.json" > "${temp_dir}/reference.md" <<'PY'
import json
import sys

envelope = json.load(open(sys.argv[1], encoding="utf-8"))
catalog = envelope["data"]["catalog"]
if envelope.get("ok") is not True or catalog.get("schema_version") != 1:
    raise SystemExit("ERROR: unsupported or failed operation catalog")
operations = catalog["operations"]
if not isinstance(operations, list) or not operations:
    raise SystemExit("ERROR: empty operation catalog")

def value(item):
    if item is None or item == "":
        return "—"
    if isinstance(item, (dict, list, bool)):
        return json.dumps(item, ensure_ascii=False, sort_keys=True, separators=(",", ":"))
    return str(item)

def cell(item):
    return value(item).replace("|", "\\|").replace("\r", " ").replace("\n", " ")

def code(item):
    return "`" + cell(item).replace("`", "&#96;") + "`"

print("# 命令操作目录\n")
print("<!-- Generated by scripts/build-command-docs.sh; edit the embedded operation registry. -->\n")
print("本页由运行时操作目录生成。当前主机以 `sbv commands --json` 为准；")
print("单项参数、安全分类和输入约束使用 `sbv schema <operation-id> --json` 查询。")
print("`sbv agent commands --json` 与 `sbv agent schema <operation-id> --json` 是兼容入口。")
print("操作描述不替代各协议 typed record 的校验，也不代表主机已安装或通过运行态验收。\n")
print("## 结构化操作\n")
print("完整用法中的占位符需要替换为实际值；`--json` 的 stdout 只返回一个 JSON 对象。")
print("命令具体输入、并发和服务影响与同一操作描述共同维护。\n")
for op in operations:
    if op["automation"] != "structured":
        continue
    print("### " + op["id"] + "\n")
    print(cell(op["summary"]) + "\n")
    print("```bash\n" + op["usage"] + "\n```\n")
    print("| 契约 | 值 |\n| --- | --- |")
    for name, item in (
        ("命令", "sbv " + op["command"]),
        ("Agent 兼容入口", "sbv agent " + op["agent_command"]),
        ("变更状态", op["mutation"]),
        ("敏感输出", op["sensitive"]),
        ("确认", op["confirmation"]),
        ("并发条件", op["concurrency"]),
        ("CAS", op["cas"]),
        ("输入契约", op["input_contract"]),
        ("服务影响", op["service_impact"]),
        ("外部写入", op["external_write"]),
        ("可能涉及外部写入", op["external_write_possible"]),
    ):
        print("| " + name + " | " + code(item) + " |")
    print("\n| 参数 | 类型 | 必需 | 说明与约束 |\n| --- | --- | --- | --- |")
    for parameter in op["parameters"]:
        details = {key: item for key, item in parameter.items()
                   if key not in ("name", "type", "required")}
        print("| " + " | ".join((code(parameter["name"]), code(parameter["type"]),
              code(parameter["required"]), code(details))) + " |")
    print("\n[操作说明](" + op["docs"] + ")\n")

print("## 交互操作边界\n")
print("下列遗留操作尚无结构化写入口。使用所列菜单并遵守目标环境的操作授权；")
print("不要通过拼接提示答案或直接改状态文件绕过这些边界。\n")
print("| 操作 ID | 操作 | 菜单 / 手工入口 | 副作用 / 服务影响 | 限制原因 |\n| --- | --- | --- | --- | --- |")
for op in operations:
    if op["automation"] == "interactive_only":
        print("| " + " | ".join((code(op["id"]), cell(op["summary"]),
                                  code(op["menu"]), code({"mutation": op["mutation"], "sensitive": op["sensitive"], "service_impact": op["service_impact"]}), cell(op["reason"]))) + " |")

print("\n## 既有文本命令\n")
print("这些入口可直接调用，仍使用文本结果；不要将其 stdout 当作结构化 JSON。\n")
print("| 操作 ID | 用法与别名 | 变更 / 敏感 | 确认 / 并发 | 限制 |\n| --- | --- | --- | --- | --- |")
for op in operations:
    if op["automation"] == "legacy_cli":
        print("| " + " | ".join((code(op["id"]), code([op["usage"]] + op.get("aliases", [])),
              code({"mutation": op["mutation"], "sensitive": op["sensitive"]}),
              code({"confirmation": op["confirmation"], "concurrency": op["concurrency"]}),
              cell(op["reason"]))) + " |")
PY
  if [[ "${check_only}" == y ]]; then
    if [[ ! -f "${output}" ]] || ! cmp -s -- "${temp_dir}/reference.md" "${output}"; then
      printf 'ERROR: stale command reference; run bash scripts/build-command-docs.sh\n' >&2
      return 1
    fi
    printf 'Command catalog reference is synchronized.\n'
    return 0
  fi
  staging=$(mktemp "${output}.stage.XXXXXX") || return 1
  cat "${temp_dir}/reference.md" > "${staging}" || return 1
  chmod 0644 "${staging}" || return 1
  mv -f -- "${staging}" "${output}" || return 1
  staging=''
  printf 'Generated docs/wiki/Command-Catalog.md\n'
)

main "$@"
